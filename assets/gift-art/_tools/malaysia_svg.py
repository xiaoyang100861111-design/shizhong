# ---------------------------------------------------------------- Petronas Twin Towers
def tower(cx):
    tiers = [(214, 24), (160, 22), (126, 19), (100, 16), (80, 12.5), (66, 9), (56, 6), (48, 3.5)]
    left = []
    for i, (y, hw) in enumerate(tiers):
        ny = tiers[i + 1][0] if i + 1 < len(tiers) else 40
        left.append((cx - hw, y))
        left.append((cx - hw * .96, ny + 3))
    right = [(2 * cx - x, y) for x, y in reversed(left)]
    pts = left + [(cx - 2, 41), (cx, 37), (cx + 2, 41)] + right
    s = '<path d="M%sz" fill="url(#tw)"/>' % 'L'.join('%s %s' % (n(x), n(y)) for x, y in pts)
    s += '<g stroke="#5E6F8C" stroke-opacity=".28" stroke-width="1.2">'
    for off, top in ((-15, 163), (-8, 103), (0, 69), (8, 103), (15, 163)):
        s += '<path d="M%s 212V%s"/>' % (n(cx + off), top)
    s += '</g><g fill="#F8FBFF" opacity=".95">'
    for y, hw in tiers[1:-1]:
        s += '<rect x="%s" y="%s" width="%s" height="3" rx="1.5"/>' % (n(cx - hw - 2.5), n(y), n(2 * hw + 5))
    s += '</g><g fill="#FFD36B">'
    for i, y in enumerate((196, 182, 170, 146, 136, 112, 90)):
        s += '<rect x="%s" y="%s" width="5" height="3" rx="1"/>' % (n(cx - 11 + (i * 7) % 18), y)
    s += '</g>'
    s += '<path d="M%s 40V8" stroke="#E6EDF7" stroke-width="2.6" stroke-linecap="round"/>' % n(cx)
    s += '<circle cx="%s" cy="24" r="2.6" fill="#fff"/>' % n(cx)
    return s


