# ---------------------------------------------------------------- Satay
def satay():
    out = ''
    chunk_shapes = [
        [1, .92, 1.05, .95, 1.02, .9, 1.04, .96],
        [.95, 1.04, .92, 1, .97, 1.05, .93, 1],
        [1.03, .94, 1, 1.06, .92, 1, .96, 1.04],
    ]
    px0, py0 = 50, 216
    for si, ang in enumerate((-78, -57, -36)):
        a = math.radians(ang)
        ux, uy = math.cos(a), math.sin(a)
        x0, y0 = px0 + si * 6, py0 - si * 2
        x1, y1 = x0 + ux * 196, y0 + uy * 196
        out += '<path d="M%s %sL%s %s" stroke="#9C7038" stroke-width="7" stroke-linecap="round"/>' % (n(x0), n(y0), n(x1), n(y1))
        out += '<path d="M%s %sL%s %s" stroke="url(#bb)" stroke-width="4.5" stroke-linecap="round"/>' % (n(x0), n(y0), n(x1), n(y1))
        for ci in range(4):
            d = 90 + ci * 22
            cx_, cy_ = x0 + ux * d, y0 + uy * d
            shp = chunk_shapes[(ci + si) % 3]
            pts = []
            for k in range(8):
                t = k * math.pi / 4
                ra = 12.5 * shp[k] * abs(math.cos(t)) + 15 * shp[k] * abs(math.sin(t))
                lx, ly = math.cos(t) * ra, math.sin(t) * ra
                pts.append((cx_ + lx * ux - ly * uy, cy_ + lx * uy + ly * ux))
            p = 'M%s %s' % (n((pts[0][0] + pts[1][0]) / 2), n((pts[0][1] + pts[1][1]) / 2))
            for k in range(8):
                q = pts[(k + 1) % 8]
                r_ = pts[(k + 2) % 8]
                p += 'Q%s %s %s %s' % (n(q[0]), n(q[1]), n((q[0] + r_[0]) / 2), n((q[1] + r_[1]) / 2))
            out += '<path d="%sz" fill="url(#mt)" stroke="#6E2C0B" stroke-opacity=".35" stroke-width="1.2"/>' % p
            px, py = -uy, ux
            for off, ln, w, op in ((-4, 16, 3, .5), (5, 12, 2.4, .4)):
                sx, sy = cx_ + ux * off + px * ln / 2, cy_ + uy * off + py * ln / 2
                out += '<path d="M%s %sl%s %s" stroke="#4E1F06" stroke-opacity="%s" stroke-width="%s" stroke-linecap="round"/>' % (
                    n(sx), n(sy), n(-px * ln), n(-py * ln), op, w)
            hx, hy = cx_ - px * 7 - ux * 2, cy_ - py * 7 - uy * 2
            out += '<ellipse cx="%s" cy="%s" rx="4.5" ry="2.4" transform="rotate(%s %s %s)" fill="#FFE2B8" opacity=".8"/>' % (
                n(hx), n(hy), n(ang), n(hx), n(hy))
    return out


