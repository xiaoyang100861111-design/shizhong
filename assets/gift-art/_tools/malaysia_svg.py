# ---------------------------------------------------------------- Durian
def durian():
    cx, cy, rx, ry = 124, 144, 74, 70
    light = (-0.62, -0.78)

    def shade(t):
        # t in 0..1 -> dark olive .. light lime
        dark, mid, lite = (0x4A, 0x66, 0x1C), (0x8F, 0xAE, 0x35), (0xE2, 0xEC, 0x8A)
        if t < .5:
            a, b, k = dark, mid, t / .5
        else:
            a, b, k = mid, lite, (t - .5) / .5
        return '#%02X%02X%02X' % tuple(int(a[i] + (b[i] - a[i]) * k) for i in range(3))

    def spike(bx, by, s, ox, oy, pos_light):
        ax, ay = bx + ox, by + oy
        corners = [(bx, by - s), (bx + s, by), (bx, by + s), (bx - s, by)]
        out = ''
        for i in range(4):
            p, q = corners[i], corners[(i + 1) % 4]
            mx, my = (p[0] + q[0]) / 2 - bx, (p[1] + q[1]) / 2 - by
            l = math.hypot(mx, my) or 1
            d = (mx / l) * light[0] + (my / l) * light[1]
            t = max(0, min(1, .5 + .42 * d + .28 * pos_light))
            out += '<path d="M%s %sL%s %sL%s %sz" fill="%s"/>' % (n(ax), n(ay), n(p[0]), n(p[1]), n(q[0]), n(q[1]), shade(t))
        return out

    back = ''
    for k in range(22):
        a = -math.pi / 2 + k * 2 * math.pi / 22 + .07
        bx, by = cx + rx * .93 * math.cos(a), cy + ry * .93 * math.sin(a)
        if by > cy + ry * .75:
            continue
        s = 11
        pl = -(math.cos(a) * light[0] + math.sin(a) * light[1]) * -1
        back += spike(bx, by, s, math.cos(a) * 17, math.sin(a) * 17, pl * .8)
    front = []
    step = 23
    for row, y in enumerate(range(int(cy - ry) + 16, int(cy + ry) - 4, 19)):
        off = (row % 2) * step / 2
        x = cx - rx - off
        while x < cx + rx:
            u, v = (x - cx) / rx, (y - cy) / ry
            r = math.hypot(u, v)
            if r < .86:
                s = 10.5 * (1 - .32 * r)
                pl = -(u * light[0] + v * light[1]) * -1 * 0 + (-(u + v) / 1.6)
                front.append((y, spike(x, y, s, u * s * 1.3, v * s * 1.3 - 2, pl)))
            x += step
    front.sort(key=lambda t: t[0])
    return back, ''.join(f for _, f in front)


