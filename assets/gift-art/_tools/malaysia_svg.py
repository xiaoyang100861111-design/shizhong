def n(v):
    """Compact number formatting."""
    r = round(v, 1)
    return str(int(r)) if r == int(r) else str(r)


def svg(defs, body):
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">'
            '<defs>' + defs + '</defs>' + body + '</svg>')


def lg(id_, stops, x1=0, y1=0, x2=0, y2=1, extra=''):
    s = ''.join('<stop offset="%s" stop-color="%s"%s/>' % (
        o, c, (' stop-opacity="%s"' % op) if op is not None else '') for o, c, op in
        [(t + (None,))[:3] for t in stops])
    return '<linearGradient id="%s" x1="%s" y1="%s" x2="%s" y2="%s"%s>%s</linearGradient>' % (
        id_, x1, y1, x2, y2, extra, s)


def rg(id_, stops, cx=.35, cy=.3, r=.75, extra=''):
    s = ''.join('<stop offset="%s" stop-color="%s"%s/>' % (
        o, c, (' stop-opacity="%s"' % op) if op is not None else '') for o, c, op in
        [(t + (None,))[:3] for t in stops])
    return '<radialGradient id="%s" cx="%s" cy="%s" r="%s"%s>%s</radialGradient>' % (id_, cx, cy, r, extra, s)


